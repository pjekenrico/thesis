def casson_model(shear_rate, Htc, m=100):

    mu0 = 0.073 * Htc + 0.599
    tau_0 = 0.888 * Htc - 23.753

    mu = (
        np.sqrt(mu0) + np.sqrt(tau_0 * (1 - np.exp(-m * shear_rate)) / shear_rate)
    ) ** 2

    return mu


